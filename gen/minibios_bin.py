#!/usr/bin/env python3
"""gen/minibios_bin.py -- turn the assembled firmware (tests/minibios.asm -> build/minibios.bin)
into a C translation unit the APE carries.

The boot mode needs the firmware as BYTES IN THE BINARY: the port's target is an Actually
Portable Executable that must boot a kernel from a clean directory, and the REFERENCE leg
must get the same bytes from the same file (oracle/run-boot.mjs reads build/minibios.bin), so
the file is the source of truth and this is only its carrier.  `make` regenerates it whenever
the assembly or the binary changes, so the embedded copy can never be stale.

    usage: gen/minibios_bin.py <input.bin> <output.c>
"""

import sys


def main(argv):
    if len(argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    src, dst = argv[1], argv[2]

    data = open(src, "rb").read()

    with open(dst, "w") as out:
        out.write("/*\n")
        out.write(" * %s -- GENERATED by gen/minibios_bin.py from %s.  Do not edit.\n"
                  % (dst.split("/")[-1], src))
        out.write(" *\n")
        out.write(" * %d bytes: the 64 KiB firmware image tests/minibios.asm assembles to, carried\n"
                  % len(data))
        out.write(" * in the APE so the boot mode needs no data file beside it.\n")
        out.write(" */\n\n")
        out.write("const unsigned char v86c_minibios_image[] = {\n")
        for i in range(0, len(data), 16):
            out.write("\t" + " ".join("0x%02x," % b for b in data[i:i + 16]) + "\n")
        out.write("};\n\n")
        out.write("const unsigned int v86c_minibios_image_len = %d;\n" % len(data))

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
