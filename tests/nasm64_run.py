#!/usr/bin/env python3
"""Differential oracle for the x86-64 corpus (tests/nasm64/*.asm, S4).

THE 32-BIT LANE'S SHAPE, FOR 64 BITS (results/x86-64-plan.md ss2.1):

    tests/nasm64/<t>.asm
      -> as --64                     (gas, .intel_syntax noprefix; generated by
      -> ld -T tests/nasm64.ld        gen/nasm64_gen.py, never hand-edited)
      -> objcopy -O binary           a flat image at its link base 0x80000
      -> build/mkfixture64           the NATIVE leg: mmap at the link base, jump to the
                                     body, dump the v2 document (ptrace ground truth)
      -> the port                    --fixture64: the same v2 document from the emulator
      -> compare                     the 32-bit comparison's logic, at 64-bit widths

THE COMPARISON IS THE 32-BIT ONE (tests/nasm_run.py:156-255, a transcription of
v86/tests/nasm/run.js:384-510) ON THE v2 LAYOUT, field for field: the 16 GPRs at 64
bits, rip, st0-7 with the same FPU_TAG_ALL_INVALID branch, mm0-7, xmm0-7, the 8 KiB
window at 0x100000, `rflags & MASK_ARITH`, and the exception kind + the faulting rip.
Two deliberate differences, both stated at the code:

  * the register file is 16 x u64 and rip is 64-bit, so a mismatch above 2^32 is
    DETECTED -- the 32-bit document's values are masked to 32 bits by the same
    comparison (run.js's `& 0xFFFFFFFF`), and widening that mask is what makes the
    64-bit lane's first comparisons meaningful;
  * the compared flag mask is NOT widened in this slice (plan ss2.1.3): `MASK_ARITH` is
    upstream's mask, because a mask is a claim about what the emulator models.

STAGES.  translate / fixtures / run / all, plus:

  --stage control   THE HARNESS'S OWN CONTROL (this slice's gate item (c)): assemble the
                    HAND-WRITTEN tests/nasm64_control.asm, run the native harness on it,
                    and check the document against an INDEPENDENT Python model of what
                    its body wrote -- the breakpoint hit at `loop`, the 8 KiB window's
                    bytes, the 16 GPRs, the flags, and the all-empty x87 tag word. If
                    that fails, the harness is broken and no corpus result means
                    anything.

  --expect MODE     what the run's outcome must BE (the exit code is the gate):
                      all-green       every test agrees            (the default)
                      all-red-named   every test stops with "--fixture64"'s
                                      `v86c: unimplemented: <symbol>`
                      all-failing     every test MISMATCHES, and (with --expect-field)
                                      on the named field -- the PERTURBED-FIXTURE
                                      control, which proves the comparison bites
                      counts          (with --expect-counts) the SUMMARY NUMBERS are
                                      exactly what was declared -- the mode S4's gate
                                      uses, because "a stop exists" cannot tell
                                      progress from catastrophe (round 2, fix 6)
                    There is deliberately no permissive mode: a verdict that passes on
                    any outcome is not a verdict.
  --perturb-field   reg|mem|rip|none: with --stage fixtures, also write a PERTURBED copy
                    of every fixture into --perturb-dir (one 64-bit word or the rip +1),
                    for --reuse-fixtures to feed back as the negative control.

usage:
    python3 tests/nasm64_run.py --stage all \\
        --actual "build/v86c-nasm64 {img} {limit} --fixture64"
    python3 tests/nasm64_run.py --stage all --actual "build/mkfixture64 {img} {body} {loop}"

Read-only: v86/ is never written to, and tests/nasm_run.py is never edited (the
2116-arity check there is a property of the 32-bit contract and must not be taught a
second shape -- plan ss2.1.1).
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

CORPUS_DIR = HERE / "nasm64"
CONTROL_SRC = HERE / "nasm64_control.asm"
LINKER_SCRIPT = HERE / "nasm64.ld"
WORKDIR = ROOT / "build" / "nasm64"
HARNESS = ROOT / "build" / "mkfixture64"

# the v2 document's arity and layout (tests/mkfixture64.c's header comment)
V2_LEN = 16 + 1 + 8 + 16 + 32 + 2048 + 1 + 1 + 1   # == 2124
V2_OFF_RIP = 16
V2_OFF_FPU = 17
V2_OFF_MMX = 25
V2_OFF_XMM = 41
V2_OFF_MEM = 73
V2_OFF_FLAGS = V2_OFF_MEM + 2048                   # 2121
V2_OFF_TAG = V2_OFF_FLAGS + 1
V2_OFF_STATUS = V2_OFF_TAG + 1
BSS = 0x100000
STACK_TOP = 0x102000

GPRS = ["rax", "rcx", "rdx", "rbx", "rsp", "rbp", "rsi", "rdi",
        "r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15"]

# run.js:49-52 -- the comparison constants, verbatim (unchanged in this slice)
MASK_ARITH = 1 | 1 << 2 | 1 << 4 | 1 << 6 | 1 << 7 | 1 << 11
FPU_TAG_ALL_INVALID = 0xAAAA
FPU_STATUS_MASK = 0xFFFF & ~(1 << 9 | 1 << 5 | 1 << 3 | 1 << 1)
FP_COMPARISON_SIGNIFICANT_DIGITS = 7

JSON_POS_INFINITY, JSON_NEG_INFINITY = "+INFINITY", "-INFINITY"
JSON_POS_NAN, JSON_NEG_NAN = "+NAN", "-NAN"
FLOAT_TRANSLATION = {
    JSON_POS_INFINITY: float("inf"),
    JSON_NEG_INFINITY: float("-inf"),
    JSON_POS_NAN: float("nan"),
    JSON_NEG_NAN: float("nan"),
}
JSON_RE = re.compile(r"---BEGIN JSON---([\s\[\]\.\+\w\":\-,]*)---END JSON---")
UNIMPLEMENTED_RE = re.compile(r"^v86c: unimplemented: (.+)$", re.M)

SIGNAL_TO_EXCEPTION = {
    "SIGFPE": "DE",
    "SIGILL": "UD",
    "SIGSEGV": "GP",
    "SIGBUS": "PF",
}


class FixtureError(Exception):
    pass


def format_value(v):
    """run.js:68-85, with the 64-bit mask: a value is printed as a hex word pair."""
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        if isinstance(v, int) or float(v).is_integer():
            return "0x%x" % (int(v) & 0xFFFFFFFFFFFFFFFF)
        return str(v)
    return str(v)


def extract_json(name, text):
    """The signal marker -> x86 exception, then the v2 array (run.js:89-135)."""
    exception = None
    for signal_name, kind in SIGNAL_TO_EXCEPTION.items():
        if "(signal %s)" % signal_name in text:
            exception = kind
            break
    text = re.sub(r"-inf\b", json.dumps(JSON_NEG_INFINITY), text)
    text = re.sub(r"\binf\b", json.dumps(JSON_POS_INFINITY), text)
    text = re.sub(r"-nan\b", json.dumps(JSON_NEG_NAN), text)
    text = re.sub(r"\bnan\b", json.dumps(JSON_POS_NAN), text)
    m = JSON_RE.search(text)
    if not m:
        raise FixtureError("no JSON in the document for %s" % name)
    try:
        array = json.loads(m.group(1))
    except json.JSONDecodeError as e:
        raise FixtureError("unparseable JSON in %s: %s" % (name, e))
    return {"array": array, "exception": exception}


def float_equal(x, y):
    """run.js:54-66."""
    if x == float("inf") and y == float("inf"):
        return True
    if x == float("-inf") and y == float("-inf"):
        return True
    if x != x and y != y:
        return True
    return abs(x - y) < 10.0 ** -FP_COMPARISON_SIGNIFICANT_DIGITS


def slice_v2(name, document):
    a = document["array"]
    if len(a) != V2_LEN:
        raise FixtureError("bad v2 document length in %s: %d vs %d" % (name, len(a), V2_LEN))
    regs = a[0:16]
    rip = a[V2_OFF_RIP]
    fpu = a[V2_OFF_FPU:V2_OFF_FPU + 8]
    mmx = a[V2_OFF_MMX:V2_OFF_MMX + 16]
    xmm = a[V2_OFF_XMM:V2_OFF_XMM + 32]
    memory = a[V2_OFF_MEM:V2_OFF_MEM + 2048]
    flags = a[V2_OFF_FLAGS] & MASK_ARITH
    tag = a[V2_OFF_TAG]
    status = a[V2_OFF_STATUS] & FPU_STATUS_MASK
    return regs, rip, fpu, mmx, xmm, memory, flags, tag, status


def compare(name, expected_text, actual_text):
    """The 32-bit comparison (tests/nasm_run.py:156-255) on the v2 layout."""
    expected = extract_json(name, expected_text)
    actual = extract_json(name, actual_text)
    failures = []

    def fail(fname, exp, act):
        failures.append({"name": fname, "expected": format_value(exp), "actual": format_value(act)})

    exp_regs, exp_rip, exp_fpu, exp_mmx, exp_xmm, exp_mem, exp_flags, exp_tag, exp_status = \
        slice_v2(name, expected)
    act_regs, act_rip, act_fpu, act_mmx, act_xmm, act_mem, act_flags, _act_tag, act_status = \
        slice_v2(name, actual)
    exp_fpu = [FLOAT_TRANSLATION.get(x, x) for x in exp_fpu]
    # an "invalid" entry cannot be compared; run.js only skips it on the expected side, so
    # map it to NaN on the actual side (float_equal(NaN, NaN) is true by run.js:59)
    act_fpu = [x if isinstance(x, (int, float)) else float("nan") for x in act_fpu]

    if not expected["exception"]:
        for i in range(16):
            if act_regs[i] != exp_regs[i]:
                fail("reg64[%d] (%s)" % (i, GPRS[i]), exp_regs[i], act_regs[i])

        # the same G0 repair the 32-bit runner carries (nasm_run.py:202-222): the fixture
        # prints the tag word with the kernel's | 0xffff0000 high half, so the MMX branch
        # is taken exactly when the LOW 16 bits are FPU_TAG_ALL_INVALID -- upstream's raw
        # `!==` against the 16-bit constant is unreachable, and the mm registers would be
        # compared by nothing.
        if (exp_tag & 0xFFFF) != FPU_TAG_ALL_INVALID:
            for i in range(8):
                if exp_fpu[i] != "invalid" and not float_equal(act_fpu[i], exp_fpu[i]):
                    fail("st%d" % i, exp_fpu[i], act_fpu[i])
            if exp_status != act_status:
                fail("fpu status word", exp_status, act_status)
        else:
            for i in range(16):
                if act_mmx[i] != exp_mmx[i]:
                    fail("mm%d.int32[%d]" % (i >> 1, i & 1), exp_mmx[i], act_mmx[i])

        for i in range(32):
            if act_xmm[i] != exp_xmm[i]:
                fail("xmm%d.int32[%d]" % (i >> 2, i & 3), exp_xmm[i], act_xmm[i])

        for i in range(2048):
            if act_mem[i] != exp_mem[i]:
                fail("mem[%X]" % (BSS + 4 * i), exp_mem[i], act_mem[i])

        if act_flags != exp_flags:
            fail("rflags", exp_flags, act_flags)

    if expected["exception"]:
        if act_rip != exp_rip:
            fail("exception rip", exp_rip, act_rip)

    if expected["exception"] != actual["exception"]:
        fail("Exception", expected["exception"], actual["exception"])

    return failures


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def corpus():
    return sorted(p.stem for p in CORPUS_DIR.glob("*.asm"))


def symbols(img):
    """body_start / loop from the image's ELF (tests/nasm64.ld fixes the sections)."""
    out = run(["nm", str(img.with_suffix(".elf"))])
    if out.returncode != 0:
        raise FixtureError("nm failed on %s: %s" % (img.with_suffix(".elf"), out.stderr.strip()))
    found = {}
    for line in out.stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] in ("body_start", "loop"):
            found[parts[2]] = int(parts[0], 16)
    for needed in ("body_start", "loop"):
        if needed not in found:
            raise FixtureError("no `%s` symbol in %s" % (needed, img.with_suffix(".elf")))
    return found


def translate(name, workdir, source=None):
    """as --64 -> ld -T tests/nasm64.ld -> objcopy: a flat image at its link base."""
    workdir.mkdir(parents=True, exist_ok=True)
    src = Path(source) if source else CORPUS_DIR / ("%s.asm" % name)
    s, o, elf, img = (workdir / ("%s.%s" % (name, ext)) for ext in ("s", "o", "elf", "img"))
    s.write_text(src.read_text())
    rc = run(["as", "--64", "-mx86-used-note=no", "-o", str(o), str(src)])
    if rc.returncode != 0:
        raise FixtureError("assemble failed: %s" % rc.stderr.strip())
    rc = run(["ld", "-m", "elf_x86_64", "-z", "noseparate-code", "-T", str(LINKER_SCRIPT),
              "-o", str(elf), str(o)])
    if rc.returncode != 0:
        raise FixtureError("link failed: %s" % rc.stderr.strip())
    rc = run(["objcopy", "-O", "binary", str(elf), str(img)])
    if rc.returncode != 0:
        raise FixtureError("objcopy failed: %s" % rc.stderr.strip())
    return img


def make_fixture(name, img, harness, fixture_dir):
    fixture_dir.mkdir(parents=True, exist_ok=True)
    syms = symbols(img)
    out = run([str(harness), str(img), hex(syms["body_start"]), hex(syms["loop"])])
    if out.returncode != 0:
        raise FixtureError("mkfixture64 failed on %s: %s" % (name, out.stderr.strip()))
    path = fixture_dir / ("%s.fixture" % name)
    path.write_text(out.stdout)
    return path, out.stdout


def perturb(text, field):
    """The NEGATIVE CONTROL's mechanism: change ONE value of a native document.

    One 64-bit word of the first GPR, one 32-bit word of the compared memory window, or
    the rip.  Each is a value the comparison NAMES, so a comparison that reports nothing
    after this is a comparison that does not bite.  The document is re-serialized; the
    fields the comparison reads are unchanged except the perturbed one ("invalid" and the
    float tokens survive as JSON values, which is how the harness writes them).
    """
    m = JSON_RE.search(text)
    if not m:
        raise FixtureError("cannot perturb: no JSON")
    array = json.loads(re.sub(r"-inf\b", json.dumps(JSON_NEG_INFINITY),
                              re.sub(r"\binf\b", json.dumps(JSON_POS_INFINITY),
                                     m.group(1))))
    if field == "reg":
        array[0] = (array[0] + 1) & 0xFFFFFFFFFFFFFFFF
    elif field == "mem":
        array[V2_OFF_MEM] = (array[V2_OFF_MEM] + 1) & 0xFFFFFFFF
    elif field == "rip":
        array[V2_OFF_RIP] = array[V2_OFF_RIP] + 1
    else:
        raise FixtureError("unknown perturbation field %r" % field)
    return text[:m.start(1)] + "\n" + json.dumps(array) + "\n" + text[m.end(1):]


def actual_state(name, img, actual, limit):
    """One invocation of the actual leg.  Returns (stdout, unimplemented_symbol)."""
    syms = symbols(img)
    cmd = [a.replace("{img}", str(img)).replace("{limit}", str(limit))
            .replace("{body}", hex(syms["body_start"])).replace("{loop}", hex(syms["loop"]))
            .replace("{name}", name)
           for a in actual.split()]
    out = run(cmd)
    if out.returncode != 0:
        m = UNIMPLEMENTED_RE.search(out.stderr)
        if m:
            # S2's refusal and the dispatcher's unimplemented path both land here: a NAMED
            # STOP, which is the RED state this slice's gate requires (plan ss2.1.7b)
            return None, m.group(1).strip()
        raise FixtureError("actual leg failed on %s (exit %d): %s"
                           % (name, out.returncode, out.stderr.strip()))
    return out.stdout, None


def shape(args):
    """THE DOCUMENT-SHAPE CONTROL: the 32-bit document and the v2 document, same machine.

    `--fixture` and `--fixture64` are the SAME printer, and this is what says so: run one
    image both ways and require

      * 2116 and 2124 elements (the two contracts' arities),
      * the same eight registers (the wide block's low halves: reg64[i] as u64 versus the
        narrow document's (int32_t)(uint32_t)),
      * R8-R15 zero in the wide block (they do not exist in the model yet -- the seat),
      * the same rip/eip,
      * the SAME x87/MMX/XMM/memory/flags/tag/status block,

    i.e. the wide document adds exactly the eight missing registers and widens rip, and
    changes no other byte's meaning.  Run on a 32-bit image because the port cannot execute
    a 64-bit one yet (S5): this is the only way the v2 PRINTER can be exercised today, and
    a printer that only ever runs from S5 on is a seat nobody has sat in.
    """
    image = Path(args.shape_image)
    if not image.exists():
        print("error: %s does not exist (make image builds it)" % image, file=sys.stderr)
        return 2
    binary = args.binary

    def document(flag):
        # the port is an APE: its kernel exec path needs a shell, exactly as
        # build/v86c-nasm's launcher comment records
        out = run(["/bin/sh", "-c", "%s %s %d %s" % (binary, image, args.limit, flag)])
        if out.returncode != 0:
            raise FixtureError("%s exited %d: %s" % (flag, out.returncode, out.stderr.strip()))
        return extract_json("shape", out.stdout)

    narrow = document("--fixture")
    wide = document("--fixture64")
    a = narrow["array"]
    b = wide["array"]
    clauses = []
    def clause(ok, text):
        clauses.append((ok, text))

    clause(len(a) == 2116, "the 32-bit document has 2116 elements (got %d)" % len(a))
    clause(len(b) == V2_LEN, "the v2 document has %d elements (got %d)" % (V2_LEN, len(b)))
    clause(b[8:16] == [0] * 8, "the v2 register block's R8-R15 slots are zero (the seat)")
    same = all((a[i] & 0xFFFFFFFF) == (b[i] & 0xFFFFFFFF) for i in range(8))
    clause(same, "the same eight registers (low halves and signs agree)")
    clause(a[8] == b[V2_OFF_RIP], "the same rip/eip (%d vs %d)" % (a[8], b[V2_OFF_RIP]))
    clause(a[9:] == b[V2_OFF_FPU:],
           "the x87/MMX/XMM/memory/flags/tag/status block is identical")
    width = max(len(t) for _, t in clauses)
    for ok, text in clauses:
        print("%s %-*s" % ("ok  " if ok else "FAIL", width, text))
    good = sum(1 for ok, _ in clauses if ok)
    print("[+] shape: %d/%d clause(s) held" % (good, len(clauses)))
    return 0 if good == len(clauses) else 1


def control(args):
    """(c) THE HARNESS'S OWN CONTROL, against an independent Python model."""
    if not HARNESS.exists():
        print("error: %s not built (make nasm64 builds it)" % HARNESS, file=sys.stderr)
        return 2
    workdir = Path(args.workdir)
    img = translate("control", workdir, source=CONTROL_SRC)
    syms = symbols(img)
    out = run([str(HARNESS), str(img), hex(syms["body_start"]), hex(syms["loop"])])
    if out.returncode != 0:
        print("[-] control: the harness failed: %s" % out.stderr.strip(), file=sys.stderr)
        return 1
    doc = extract_json("control", out.stdout)
    regs, rip, _fpu, mmx, xmm, mem, flags, tag, status = slice_v2("control", doc)

    # THE MODEL: what the body wrote, recomputed here from the source's constants.
    MASK64 = (1 << 64) - 1
    expected_regs = {"rax": 0x0123456789ABCDEF, "rcx": 0xFEDCBA9876543210,
                     "rdx": 0, "rbx": 0, "rsp": STACK_TOP, "rbp": 0, "rsi": 0, "rdi": 0}
    for i, reg in enumerate(GPRS[8:], start=8):
        expected_regs[reg] = 0
    window = bytearray(0x2000)
    for i in range(16):                       # qword i at 0x100000 + 8*i
        window[8 * i:8 * i + 8] = (0x1000000000000000 + i).to_bytes(8, "little")
    for i in range(8):                        # 8 x 0xA5A5A5A5A5A5A5A5 at 0x100200
        window[0x200 + 8 * i:0x200 + 8 * i + 8] = (0xA5A5A5A5A5A5A5A5).to_bytes(8, "little")
    expected_mem = [int.from_bytes(window[4 * i:4 * i + 4], "little", signed=True)
                    for i in range(2048)]

    clauses = []
    def clause(ok, text):
        clauses.append((ok, text))

    clause(doc["exception"] is None,
           "the `loop` breakpoint was hit (a dead harness reports a fault or never stops)")
    clause(rip == syms["loop"], "the document's rip is the `loop` symbol (0x%x vs 0x%x)"
           % (rip, syms["loop"]))
    def signed64(v):
        """the document prints a 64-bit value as SIGNED decimal (both producers do)"""
        v &= (1 << 64) - 1
        return v - (1 << 64) if v >> 63 else v

    for i, reg in enumerate(GPRS):
        want = signed64(expected_regs[reg])
        clause(regs[i] == want,
               "reg64[%d] (%s) == %d (0x%x); got %d" % (i, reg, want, expected_regs[reg], regs[i]))
    # CF (from `stc`) | PF and ZF (from the last `xor`), masked the way the comparison
    # masks every flag word: bits 0, 2, 4, 6, 7 and 11 only
    expected_flags = MASK_ARITH & (1 | 1 << 2 | 1 << 6)
    clause(flags == expected_flags,
           "rflags & MASK_ARITH == 0x%x (CF|PF|ZF: `stc` over the last `xor`'s flags)"
           % expected_flags)
    mismatched = [(BSS + 4 * i, expected_mem[i], mem[i])
                  for i in range(2048) if mem[i] != expected_mem[i]]
    clause(not mismatched,
           "the 8 KiB window matches the model byte for byte (%d word(s) differ%s)"
           % (len(mismatched), "" if not mismatched else
              ", first mem[%X] expected %d got %d" % mismatched[0]))
    # the FPU half: `fld1` after fninit puts 1.0 in PHYSICAL register 7 (top becomes 7), which
    # is LOGICAL st0 -- and this harness's st_space slot i is logical st(i), so the value is
    # in slot 0 while the abridged FTW marks bit 7 present (MEASURED; see the harness's
    # calibrate_ftw).  The seven registers that hold nothing are EMPTY by the hardware's own
    # tag word, not "because their slots are zero".
    clause(_fpu[0] == 1.0, "logical st0 == 1.0 (the one `fld1`; got %r)" % (_fpu[0],))
    clause(all(x == "invalid" for x in _fpu[1:]),
           "logical st1-st7 are untouched (reported invalid)")
    clause((tag & 0xFFFF) == 0x2AAA,
           "the x87 tag word's low half is 0x2AAA (physical 7 -- logical st0 -- present, "
           "seven empty; got 0x%X)" % (tag & 0xFFFF))
    clause((tag & 0xFFFF0000) == 0xFFFF0000,
           "the tag word's high half is 0xFFFF (the kernel's convert_from_fxsr form)")
    # the status word carries TOP in bits 11-13: one push leaves TOP == 7 (0x3800), which
    # is a prediction about the same `fld1` from the other side
    clause(status == (0x3800 & FPU_STATUS_MASK),
           "the x87 status word is 0x%X (TOP == 7 after one push; got 0x%X)"
           % (0x3800 & FPU_STATUS_MASK, status))
    expected_mmx = [[0, 0]] * 7 + [[0, -2147483648]]   # physical 7 = 1.0 (significand 0x80..)
    clause(mmx == [w for pair in expected_mmx for w in pair],
           "mm0-7 are the low 64 bits of the physical st slots (%r)" % (mmx,))
    clause(all(x == 0 for x in xmm), "xmm0-7 are all zero")

    width = max(len(t) for _, t in clauses)
    for ok, text in clauses:
        print("%s %-*s" % ("ok  " if ok else "FAIL", width, text))
    good = sum(1 for ok, _ in clauses if ok)
    print("[+] control: %d/%d clause(s) held" % (good, len(clauses)))
    return 0 if good == len(clauses) else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", default="run",
                    choices=("translate", "fixtures", "run", "all", "control", "shape"))
    ap.add_argument("--binary", default="./build/v86c",
                    help="the port binary the `shape` stage drives")
    ap.add_argument("--shape-image", default="tests/test.img",
                    help="a 32-bit multiboot image for the `shape` stage")
    ap.add_argument("--actual", default="js",
                    help="the actual leg's command; {img} {limit} {body} {loop} {name} "
                         "are substituted.  The native harness works too "
                         "('build/mkfixture64 {img} {body} {loop}'), which is how the "
                         "negative controls make the comparison PASS on purpose")
    ap.add_argument("--filter", default=None,
                    help="regex over test names")
    ap.add_argument("--exclude", default=None,
                    help="regex: names to leave out.  The negative controls need it: for a "
                         "FAULTING case the comparison compares the exception kind and the "
                         "faulting rip only (run.js:497-505), so a perturbed register or "
                         "memory word cannot be detected there -- a property of the "
                         "comparison, stated rather than worked around")
    ap.add_argument("--workdir", default=str(WORKDIR))
    ap.add_argument("--fixture-dir", default=None,
                    help="generate/read native fixtures here (default: workdir)")
    ap.add_argument("--reuse-fixtures", action="store_true",
                    help="read the native fixture from --fixture-dir instead of regenerating")
    ap.add_argument("--perturb-field", default="none", choices=("none", "reg", "mem", "rip"),
                    help="with --stage fixtures: also write a perturbed copy of every "
                         "fixture into --perturb-dir (the negative control's input)")
    ap.add_argument("--perturb-dir", default=None)
    ap.add_argument("--expect", default="all-green",
                    choices=("all-green", "all-red-named", "all-failing", "counts"),
                    help="the verdict the run's outcome must produce (the exit code is the "
                         "gate).  'counts' requires --expect-counts, which asserts the "
                         "SUMMARY NUMBERS rather than a stop or a shape -- round 2, fix 6: "
                         "'all-red-named' alone cannot tell progress from catastrophe once "
                         "a family starts passing, and a permissive mode would pass a "
                         "corpus in which every case disagrees")
    ap.add_argument("--expect-counts", default=None,
                    help="with --expect counts: 'green=0 red_unimplemented=57 mismatch=0 "
                         "error=0' (any subset of the SUMMARY's keys; each named key must "
                         "match EXACTLY)")
    ap.add_argument("--expect-field", default=None,
                    help="with --expect all-failing: a substring every failure set must contain")
    ap.add_argument("--limit", type=int, default=1000000,
                    help="instruction limit for the actual leg")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    if args.stage == "control":
        return control(args)
    if args.stage == "shape":
        return shape(args)

    workdir = Path(args.workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    fixture_dir = Path(args.fixture_dir) if args.fixture_dir else workdir
    fixture_dir.mkdir(parents=True, exist_ok=True)
    perturb_dir = Path(args.perturb_dir) if args.perturb_dir else workdir / "perturb"

    names = corpus()
    if args.filter:
        rx = re.compile(args.filter)
        names = [n for n in names if rx.search(n)]
    if args.exclude:
        rx = re.compile(args.exclude)
        names = [n for n in names if not rx.search(n)]
    if not names:
        print("no tests selected", file=sys.stderr)
        return 2
    if args.stage in ("fixtures", "run", "all") and not HARNESS.exists():
        print("error: %s not built (make nasm64 builds it)" % HARNESS, file=sys.stderr)
        return 2

    translated = fixtured = 0
    failed_to_build, results, red, errors = [], [], {}, []
    all_failure_names = {}
    for name in names:
        try:
            img = workdir / ("%s.img" % name)
            if args.stage in ("translate", "all") or not img.exists():
                img = translate(name, workdir)
                translated += 1
            if args.stage in ("fixtures", "all"):
                _path, fixture_text = make_fixture(name, img, HARNESS, fixture_dir)
                fixtured += 1
                if args.perturb_field != "none":
                    perturb_dir.mkdir(parents=True, exist_ok=True)
                    (perturb_dir / ("%s.fixture" % name)).write_text(
                        perturb(fixture_text, args.perturb_field))
            if args.stage in ("run", "all"):
                # ROUND 2, FIX 1 (the review's BLOCKER): `fixture_text` used to be bound
                # only by the `fixtures`/`all` stages or by `--reuse-fixtures`, so a bare
                # `--stage run` raised UnboundLocalError at the FIRST CASE THAT STOPPED
                # BEING RED -- and gate step D is exactly that form, i.e. the harness would
                # have been dead on arrival for S5, the slice it exists for.  A run-stage
                # case that has no fixture supplied generates its own here (that is what
                # the `all` stage does anyway; the stages stay separable).
                if args.reuse_fixtures:
                    fixture_path = fixture_dir / ("%s.fixture" % name)
                    if not fixture_path.exists():
                        raise FixtureError("--reuse-fixtures: no %s" % fixture_path)
                    fixture_text = fixture_path.read_text()
                elif args.stage == "run":
                    _path, fixture_text = make_fixture(name, img, HARNESS, fixture_dir)
                    fixtured += 1
                actual_text, symbol = actual_state(name, img, args.actual, args.limit)
                if symbol is not None:
                    red[name] = symbol
                    if not args.quiet:
                        print("RED %s: unimplemented: %s" % (name, symbol))
                    continue
                if not args.quiet:
                    print("Testing %s.img" % name)
                failures = compare(name, fixture_text, actual_text)
                all_failure_names[name] = {f["name"] for f in failures}
                results.append((name, failures))
        except FixtureError as e:
            errors.append((name, str(e)))

    if args.stage == "translate":
        print("\n[+] Translated + assembled + linked %d/%d file(s)" % (translated, len(names)))
    if args.stage in ("fixtures", "all", "run"):
        if fixtured:
            print("\n[+] Generated %d/%d native fixture(s)" % (fixtured, len(names)))
            if args.perturb_field != "none":
                print("[~] and %d perturbed cop(ies) in %s (field %s)"
                      % (fixtured, perturb_dir, args.perturb_field))
    if errors:
        print("\n[!] %d test(s) could not run:" % len(errors))
        for name, err in errors:
            print("\n[-] %s:\n\t%s" % (name, err))

    total = len(names)
    green = sum(1 for _n, f in results if not f)
    mismatch = sum(1 for _n, f in results if f)
    print("\n[+] SUMMARY: total=%d green=%d red_unimplemented=%d mismatch=%d error=%d"
          % (total, green, len(red), mismatch, len(errors)))
    if red:
        symbols_seen = {}
        for symbol in red.values():
            symbols_seen[symbol] = symbols_seen.get(symbol, 0) + 1
        print("[~] %d test(s) RED with a NAMED stop (plan ss2.1.7b):" % len(red))
        for symbol, count in sorted(symbols_seen.items(), key=lambda kv: -kv[1]):
            print("\t%3d x  unimplemented: %s" % (count, symbol))
    if mismatch:
        print("[-] %d test(s) MISMATCHED:" % mismatch)
        for name, failures in results:
            if not failures:
                continue
            print("\n[-] %s.img: %d field(s)" % (name, len(failures)))
            for f in failures[:12]:
                print("\n\t" + f["name"])
                print("\tActual:   " + f["actual"])
                print("\tExpected: " + f["expected"])
            if len(failures) > 12:
                print("\n\t... %d more" % (len(failures) - 12))

    # ---------------------------------------------------------------- the gate's verdict
    if args.stage in ("translate", "fixtures"):
        # a build stage has no verdict to give: the gate is about a RUN
        return 0 if not errors else 1
    if args.expect == "counts":
        if not args.expect_counts:
            print("error: --expect counts needs --expect-counts", file=sys.stderr)
            return 2
        counts = {"total": total, "green": green, "red_unimplemented": len(red),
                  "mismatch": mismatch, "error": len(errors)}
        wanted = {}
        for item in args.expect_counts.replace(",", " ").split():
            key, _, value = item.partition("=")
            key = key.strip()
            if key not in counts:
                print("error: --expect-counts: unknown key %r (known: %s)"
                      % (key, ", ".join(sorted(counts))), file=sys.stderr)
                return 2
            try:
                wanted[key] = int(value)
            except ValueError:
                print("error: --expect-counts: %r is not an integer" % value, file=sys.stderr)
                return 2
        wrong = {k: (v, counts[k]) for k, v in wanted.items() if counts[k] != v}
        for key in sorted(wrong):
            print("[-] %s: expected %d, got %d" % (key, wrong[key][0], wrong[key][1]))
        ok = not wrong
        why = ("the SUMMARY counts are exactly %s (got %s)"
               % (", ".join("%s=%d" % kv for kv in sorted(wanted.items())),
                  ", ".join("%s=%d" % kv for kv in sorted(counts.items()))))
        print("[%s] %s -- %s" % ("GATE OK" if ok else "GATE FAILED", args.expect, why))
        return 0 if ok else 1
    if args.expect == "all-green":
        ok = green == total and not errors
        why = "every test agrees (%d/%d)" % (green, total)
    elif args.expect == "all-red-named":
        ok = len(red) == total and not errors
        why = ("every test stops with a named `unimplemented:` (S4: the machine cannot "
               "run 64-bit yet, so a GREEN test here would have tested nothing)")
    else:                                   # all-failing
        ok = mismatch == total and not errors
        if ok and args.expect_field:
            missing = [name for name, names_seen in all_failure_names.items()
                       if not any(args.expect_field in n for n in names_seen)]
            if missing:
                ok = False
                print("[-] %d test(s) failed WITHOUT naming %r: %s"
                      % (len(missing), args.expect_field, ", ".join(missing[:6])))
        why = "every test mismatches on the perturbed field"
    print("[%s] %s -- %s" % ("GATE OK" if ok else "GATE FAILED", args.expect, why))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
